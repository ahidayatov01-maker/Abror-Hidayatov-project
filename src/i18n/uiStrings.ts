export function getExtendedUIStrings(lang: LanguageCode): ExtendedUIStrings {
  return EXTENDED_UI_STRINGS[lang] || EXTENDED_UI_STRINGS.en;
}

export function translateContinentName(continent: string, lang: LanguageCode): string {
  const ui = getExtendedUIStrings(lang);
  if (continent === 'all') return ui.continents.all;
  if (continent === 'All cities') return ui.continents.allCities;
  const map = ui.continents as Record<string, string>;
  return map[continent] || continent;
}
