export function getCuratedFallbackCampusImage(seedKey = 'default'): string {
  let hash = 0;
  for (let i = 0; i < seedKey.length; i++) {
    hash = (hash * 31 + seedKey.charCodeAt(i)) >>> 0;
  }
  return FALLBACK_CAMPUS_IMAGES[hash % FALLBACK_CAMPUS_IMAGES.length];
}

export function getUniversityCampusImageUrl(
  slug?: string | null,
  explicitImageUrl?: string | null
): string {
  if (explicitImageUrl && explicitImageUrl.trim().length > 0) {
    return explicitImageUrl.trim();
  }
  if (slug && UNIVERSITY_CAMPUS_IMAGES[slug]) {
    return UNIVERSITY_CAMPUS_IMAGES[slug];
  }
  return getCuratedFallbackCampusImage(slug || 'default');
}

