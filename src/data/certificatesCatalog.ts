export type CertificateCategoryId =
  | 'languages'
  | 'math_science'
  | 'it_tech'
  | 'business_pro'
  | 'other_international';

export type ScoringFormatType =
  | 'band'
  | 'numeric'
  | 'level'
  | 'pass_fail'
  | 'grade'
  | 'award'
  | 'multi_component';

export type CertificateReliabilityStatus =
  | 'verified'
  | 'estimated'
  | 'requires_verification';

export interface CertificateScoringModel {
  format: ScoringFormatType;
  scaleLabel: string;
  minScore?: number | null;
  maxScore?: number | null;
  step?: number;
  levels?: string[];
  passingRequirement: string;
  scoreInterpretation: string;
  components?: string[];
}

export interface CertificateFeeInfo {
  approximateAmount: number | null;
  currency: string;
  displayText: string;
  regionalNote: string;
  isEstimate: boolean;
  lastVerifiedAt: string;
}

export interface CertificateRecord {
  id: string;
  officialName: string;
  shortName: string;
  category: CertificateCategoryId;
  subcategory: string;
  languageOrSubject: string;
  issuingOrganization: string;
  officialWebsite: string;
  examFormat: string;
  availableLevels: string[];
  scoringModel: CertificateScoringModel;
  validityPeriod: string;
  validityYearsNumeric: number | null; // null = lifetime / does not expire
  fee: CertificateFeeInfo;
  countryAvailability: string[]; // ISO codes or 'GLOBAL'
  examFrequency: string;
  registrationInfo: string;
  officialPrepResources: Array<{ label: string; url: string }>;
  popularityRank: number; // 1 = highest
  lastVerifiedAt: string;
  informationSource: string;
  reliabilityStatus: CertificateReliabilityStatus;
  summary: string;
  acceptedCountriesNote: string;
  universityRelevance: string;
  careerRelevance: string;
}

